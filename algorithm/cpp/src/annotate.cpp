void fillRect(Image& img, const Rect& r, uint8_t b, uint8_t g, uint8_t r8) {
    if (img.empty()) return;
    const int x0 = std::max(0, r.x), y0 = std::max(0, r.y);
    const int x1 = std::min(img.width, r.right()), y1 = std::min(img.height, r.bottom());
    for (int y = y0; y < y1; ++y) {
        uint8_t* row = img.row(y);
        for (int x = x0; x < x1; ++x) {
            row[3 * x + 0] = b;
            row[3 * x + 1] = g;
            row[3 * x + 2] = r8;
        }
    }
}

void drawRect(Image& img, const Rect& r, uint8_t b, uint8_t g, uint8_t r8, int thickness) {
    const int t = std::max(1, thickness);
    fillRect(img, {r.x, r.y, r.w, t}, b, g, r8);
    fillRect(img, {r.x, r.bottom() - t, r.w, t}, b, g, r8);
    fillRect(img, {r.x, r.y, t, r.h}, b, g, r8);
    fillRect(img, {r.right() - t, r.y, t, r.h}, b, g, r8);
}

void drawLine(Image& img, int x0, int y0, int x1, int y1, uint8_t b, uint8_t g, uint8_t r8) {
    int dx = std::abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
    int dy = -std::abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    while (true) {
        if (x0 >= 0 && y0 >= 0 && x0 < img.width && y0 < img.height) {
            uint8_t* p = img.pixel(x0, y0);
            p[0] = b;
            p[1] = g;
            p[2] = r8;
        }
        if (x0 == x1 && y0 == y1) break;
        const int e2 = 2 * err;
        if (e2 >= dy) {
            err += dy;
            x0 += sx;
        }
        if (e2 <= dx) {
            err += dx;
            y0 += sy;
        }
    }
}

int textWidth(const std::string& text, int scale) { return static_cast<int>(text.size()) * 6 * scale; }

int textHeight(int scale) { return 7 * scale; }

void drawText(Image& img, int x, int y, const std::string& text, uint8_t b, uint8_t g, uint8_t r8,
              int scale) {
    const int s = std::max(1, scale);
    int cursor = x;
    const int top = y - 7 * s;
    for (char c : text) {
        const uint8_t* glyph = glyphFor(c);
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (!(glyph[row] & (1u << (4 - col)))) continue;
                fillRect(img, {cursor + col * s, top + row * s, s, s}, b, g, r8);
            }
        }
        cursor += 6 * s;
    }
}

